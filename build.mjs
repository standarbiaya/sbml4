import fs from 'node:fs';
import crypto from 'node:crypto';
const here = path => new URL('./' + path, import.meta.url);
const html = fs.readFileSync(here('public/index.html'), 'utf8');
const loginHtml = fs.readFileSync(here('public/login.html'), 'utf8');
const loginJs = fs.readFileSync(here('public/login.js'), 'utf8');
const backend = fs.readFileSync(here('backend.js'), 'utf8');
const logo = fs.readFileSync(here('public/logo-kemenkeu-transparent.png')).toString('base64');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x => x[1]);
if (scripts.length !== 1) throw new Error('Dashboard harus memiliki tepat satu skrip inline untuk CSP');
const scriptHash = crypto.createHash('sha256').update(scripts[0]).digest('base64');
const built = `// Generated by npm run build. Keep secrets only in Cloudflare Runtime Secrets.\n` +
  `const DASHBOARD_HTML = ${JSON.stringify(html)};\n` +
  `const LOGIN_HTML = ${JSON.stringify(loginHtml)};\n` +
  `const LOGIN_JS = ${JSON.stringify(loginJs)};\n` +
  `const LOGO_KEMENKEU_B64 = ${JSON.stringify(logo)};\n` +
  `const DASHBOARD_SCRIPT_HASH = ${JSON.stringify(scriptHash)};\n` + backend;
fs.writeFileSync(here('worker.js'), built);
console.log('Worker siap, halaman dashboard dan API dilindungi login; logo terintegrasi.');
